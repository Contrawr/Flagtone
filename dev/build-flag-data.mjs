// Regenerates js/flagData.js by running dev/check-flags.html in headless Chromium:
// each flag's proportions and the colors that cover enough of it to be hidden.
// Fails if any flag has no hideable color, renders differently once prepared, or
// leaves a trace of a hidden color.
//
// Needs Playwright (npm i -g playwright). Usage: node dev/build-flag-data.mjs [--screenshot out.png]
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join } from 'node:path';
import { serve } from './serve.mjs';

async function loadPlaywright() {
  try {
    return await import('playwright');
  } catch {
    const root = execSync('npm root -g').toString().trim();
    return import(join(root, 'playwright', 'index.mjs'));
  }
}

const shotIndex = process.argv.indexOf('--screenshot');
const shotPath = shotIndex > 0 ? process.argv[shotIndex + 1] : null;

const { chromium } = await loadPlaywright();
const { server, url } = await serve();
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1400, height: 900 } });
  page.on('pageerror', (err) => console.error('page error:', err.message));
  await page.goto(`${url}/dev/check-flags.html?audit`);
  await page.waitForFunction(() => window.checkResult, null, { timeout: 300_000, polling: 500 });
  const { total, bad, data } = await page.evaluate(() => window.checkResult);
  if (shotPath) await page.screenshot({ path: shotPath, fullPage: true });
  if (bad.length) {
    console.error(`${bad.length} of ${total} flags have problems:\n${bad.join('\n')}`);
    process.exitCode = 1;
  } else {
    const lines = Object.keys(data).sort().map((code) => {
      const { ratio, colors } = data[code];
      const cs = colors.map((c) => {
        const also = c.also.length ? `, also: [${c.also.map((h) => `'${h}'`).join(', ')}]` : '';
        return `{ hex: '${c.hex}', share: ${c.share}${also} }`;
      });
      return `  ${code}: { ratio: ${ratio}, colors: [${cs.join(', ')}] },`;
    });
    writeFileSync(
      new URL('../js/flagData.js', import.meta.url),
      '// Generated by dev/build-flag-data.mjs. Do not edit by hand.\n' +
        '// ratio: width / height. colors: hideable colors (share of the flag\'s area);\n' +
        '// `also` lists near-identical shades that are hidden together with it.\n' +
        `export const FLAG_DATA = {\n${lines.join('\n')}\n};\n`,
    );
    console.log(`Wrote js/flagData.js for ${total} flags`);
  }
} finally {
  await browser.close();
  server.close();
}
